/**
 * `packages/core/src/deprecated.gen.ts` from `packages/core/renames.json`: the rename map as a literal, and the old names as a type whose
 * every leaf is `@deprecated` and holds what its new path holds. `pnpm tokens:build` writes it; `pnpm check deprecated` fails when it is stale.
 */

import { readFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

export const RENAMES_FILE = "packages/core/renames.json";
export const DEPRECATED_GEN = "packages/core/src/deprecated.gen.ts";
export const SINCE = "1.2.0";
const root = (p: string) => fileURLToPath(new URL(`../../../${p}`, import.meta.url));

export const readRenames = (): Record<string, string> => JSON.parse(readFileSync(root(RENAMES_FILE), "utf8")) as Record<string, string>;

const key = (k: string) => (/^[A-Za-z_$][\w$]*$/.test(k) ? k : JSON.stringify(k));
type Tree = { [k: string]: Tree | string };

export function deprecatedGen(renames: Record<string, string> = readRenames()): string {
  const entries = Object.entries(renames);
  const tree: Tree = {};
  for (const [old, now] of entries) {
    const keys = old.split(".");
    let at = tree;
    for (const k of keys.slice(0, -1)) at = (at[k] ??= {}) as Tree;
    at[keys[keys.length - 1]!] = now;
  }
  const print = (node: Tree, indent: string): string =>
    Object.entries(node)
      .map(([k, v]) =>
        typeof v === "string"
          ? `${indent}/** @deprecated since ${SINCE}: renamed to \`${v}\`. */\n${indent}${key(k)}: At<T, ${JSON.stringify(v)}>;`
          : `${indent}${key(k)}: {\n${print(v, `${indent}  `)}\n${indent}};`,
      )
      .join("\n");
  return [
    "// Generated by `pnpm tokens:build` from packages/core/renames.json. Do not edit: change that file and run the command again.",
    "",
    `export const DEPRECATED_SINCE = ${JSON.stringify(SINCE)};`,
    "",
    "/** Old token path → the path it was renamed to. */",
    entries.length ? `export const renames = {\n${entries.map(([old, now]) => `  ${JSON.stringify(old)}: ${JSON.stringify(now)},`).join("\n")}\n} as const;` : "export const renames = {} as const;",
    "",
    ...(entries.length ? ["type At<T, P extends string> = P extends `${infer Head}.${infer Rest}` ? (Head extends keyof T ? At<T[Head], Rest> : never) : P extends keyof T ? T[P] : never;", ""] : []),
    "/** The old names, each holding what its new path holds in `T` (`t` in either kit). */",
    entries.length ? `export interface DeprecatedTokens<T> {\n${print(tree, "  ")}\n}` : "// eslint-disable-next-line @typescript-eslint/no-unused-vars, @typescript-eslint/no-empty-object-type\nexport interface DeprecatedTokens<T> {}",
    "",
  ].join("\n");
}
