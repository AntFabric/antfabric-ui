/** The document as written, references and all: what the stylesheet and `tokens.json` read. */
export type TokenSource = typeof tokenSource;

/**
 * The same tree with every `"{primitives.…}"` replaced by the primitive's value and every alias of another token by that token's, so a literal is what a reader finds:
 * `tokens.themes.light.color.text.body` is `"#1a1b1e"`. What the kits, the catalogue and the scripts read.
 */
export const tokens = aliasesResolved(resolveTree(tokenSource));

/** Each set with its aliases (`"{border.subtle}"`) replaced by the value of the token they name in that set, so no reader of `tokens` meets one. */
function aliasesResolved(tree: Resolved<typeof tokenSource>): Resolved<typeof tokenSource> {
  type Set = Parameters<typeof resolveAliases>[0];
  const shared = tree.shared as Set;
  const profiles = tree.profiles as unknown as Record<string, Set>;
  // An alias is looked up in its own set, then in the sets under it. A theme stands alone: a colour is never a size.
  const each = (sets: object, name: string, under: (key: string) => Set[]) => Object.fromEntries(Object.entries(sets).map(([k, set]) => [k, resolveAliases(set as Set, `${name}.${k}`, under(k))]));
  const platform = (os: string) => (Object.keys(PLATFORM_OS) as Platform[]).find((p) => PLATFORM_OS[p].includes(os as OS))!;
  return {
    shared: resolveAliases(shared, "shared"),
    themes: each(tree.themes, "themes", () => []),
    profiles: each(tree.profiles, "profiles", () => [shared]),
    os: each(tree.os, "os", (os) => [profiles[platform(os)]!, shared]),
  } as unknown as Resolved<typeof tokenSource>;
}

/** `tokenSource` with each reference resolved, at the type level too: a reference is the literal type of its primitive. */
export type Tokens = typeof tokens;

/** The platform an OS's set extends: `android` is the phone's. */
export const platformOf = (os: OS): Platform => (Object.keys(PLATFORM_OS) as Platform[]).find((p) => PLATFORM_OS[p].includes(os))!;

// An OS set changes values, it does not add tokens: every leaf in one is a leaf of its platform's profile, or a path would exist
// on one OS only and have no description, map entry or default for the others.
{
  const leaves = (tree: object, prefix = ""): string[] =>
    Object.entries(tree).flatMap(([k, v]) => (k.startsWith("$") ? [] : typeof v === "object" ? leaves(v, `${prefix}${k}.`) : [`${prefix}${k}`]));
  const has = (tree: object, path: string) => path.split(".").reduce<unknown>((at, k) => (typeof at === "object" && at !== null ? (at as Record<string, unknown>)[k] : undefined), tree) !== undefined;
  for (const [os, set] of Object.entries(tokenSource.os)) {
    const profile = tokenSource.profiles[platformOf(os as OS) as keyof typeof tokenSource.profiles];
    for (const path of leaves(set)) if (!has(profile, path)) throw new Error(`tokens: os.${os}.${path} is not a leaf of profiles.${platformOf(os as OS)}; an OS set only overrides`);
  }
}
