/**
 * AntFabric tokens. Colours are shared by every platform and switch by theme; sizes, type and density
 * switch by platform. Values come from AntFabric's desktop app and mobile app. The web profile has no app to copy from yet; its values were confirmed by
 * design on 24 November 2026. The glass.* colours, shadow.glass and the shared glass.blur and glass.saturate are the Liquid Glass material, used only where a
 * component's `glass` layer applies (iOS 26+ and macOS 26+). glass.tinted / .solid and
 * shadow.glassContrast are what it becomes under the device's Tinted, Reduce Transparency and
 * Increase Contrast settings.
 *
 *   shared    scales every platform uses (radius, space, font, motion…)
 *   themes    colours and shadows, per theme
 *   profiles  sizes, type and density, per platform
 *   os        what one operating system changes inside its platform's profile (today: Android on the phone)
 *
 * Modes are applied in that order, the later one winning: shared, then the platform's profile, then the OS's set, then the theme.
 * An OS set holds only the leaves whose value differs from the profile's, so the profile is what iOS draws and `os.android` is
 * what Android changes (Material's 36×14 switch track against UISwitch's 51×31). A leaf in an OS set must already exist in a profile
 * (the file throws on import when it does not), so a path has one name and one description whatever the OS. React reads it as
 * `[data-af-os="android"]` under the root's `data-af-os` attribute; React Native as `resolveTokens("mobile", "light", { os: "android" })`.
 * The React kit has no OS set because nothing it draws differs between macOS, Windows, Linux and the browser beyond what `usePlatform()` already says.
 *
 * Component tokens (`switch.*`, `button.*`) name a decision that belongs to one component and differs by mode: a switch's track
 * and thumb, a button's label and icon size per size. They sit in the mode set that decides them (profiles for a size, themes for a
 * colour) and point at the product's size steps where one has the value. A token that exists in some profiles only (the phone's
 * font files) is read only by that platform's kit.
 *
 * The React kit reads these as CSS variables (`var(--af-color-background-brand-default)`, defined by
 * `tokensCss()` under `[data-af-platform]` / `[data-af-theme]`), so a theme or density switch is an
 * attribute change. The React Native kit resolves them to numbers and colours (`resolveTokens`).
 *
 * References: a leaf whose value is one of the product's primitives points at it, `"{primitives.color.neutral.900}"`, the product's own
 * DTCG spelling; `primitives.ts` mirrors them (`pnpm primitives`). A leaf has one when it has a product source in `tokens.map.json` and
 * its value equals the primitive that product token names, in each theme or profile it is defined in. A leaf that has drifted, has no
 * product token or is a composite stays a literal, so the literals are the drift list. The mobile profile points at the product's size
 * steps (`raw.44`, `fontSize.raw-16`) wherever the phone's number is one. `tokenSource` is this file's tree; `tokens`, exported below
 * it, is the same tree with each reference replaced by its value, which is what the kits and the catalogue read.
 *
 * The data components' groups (`chart`, `data`, `table`) are ours, not the product's (`unmapped` in `tokens.map.json`, confirmed by design on 24 November 2026). `data.*` is a flat pastel palette of
 * its own so no chart or KPI reads the brand or a status colour; `chart.*` and `table.*` point at the neutrals they share (`color.border.subtle` is
 * `chart.gridColor` in each theme) and hold the plot's geometry per platform.
 *
 * Paths follow one grammar (`naming.ts`): a semantic token is `category.property.role` (`color.text.onBrand`, `size.control.md`),
 * a component token is `componentId.key` (`chip.removeSize`). The product's own name for each (`--fg-on-brand`) is in `tokens.map.json`,
 * and a variable is `--af-` plus the kebab-cased path (see `vars.ts`).
 */

