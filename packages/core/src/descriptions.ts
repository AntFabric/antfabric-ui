/**
 * What each token is for: one sentence of when to use it, written once for every leaf in `tokens.ts`.
 *
 * `tokens.ts` stays the values (mode-first, so the kits' types come straight from its literals) and
 * this file holds the words. A leaf is named by its path inside its group, the way
 * `tokens.map.json` and `pnpm report` name it: `color.text.muted` is one entry whether it is read from
 * `themes.light` or `themes.dark`, and `size.control.md` is one entry for all three profiles.
 * `descriptions` is typed over every such path, so a token with no entry, or an entry for a token
 * that is gone, fails `pnpm typecheck`.
 *
 * A bare string is the description. A `TokenNote` adds what differs per profile, and marks a colour
 * that is the same in light and dark on purpose.
 */

import type { Tokens } from "./tokens";

type Leaf = string | number;

/** Every leaf path in a tree, dotted, keys starting with `$` skipped: `"size.control.iconSm"`. */
type PathsIn<T> = {
  [K in keyof T & string]: K extends `$${string}` ? never : T[K] extends Leaf ? K : `${K}.${PathsIn<T[K]>}`;
}[keyof T & string];

/**
 * A leaf of any mode: shared scales, either theme's colours and shadows, any profile's sizes, type
 * and density. The union of 212 paths; a path that exists in several modes is counted once.
 */
export type TokenPath =
  | PathsIn<Tokens["shared"]>
  | PathsIn<Tokens["themes"]["light"]>
  | PathsIn<Tokens["themes"]["dark"]>
  | PathsIn<Tokens["profiles"]["web"]>
  | PathsIn<Tokens["profiles"]["desktop"]>
  | PathsIn<Tokens["profiles"]["mobile"]>;

export interface TokenNote {
  /** When to use it, in one sentence: not what it is. Where people confuse neighbours, how it differs from them. */
  text: string;
  /** Only where the mobile profile's value or use differs from desktop's. */
  mobile?: string;
  /** Only where the web profile's value or use differs from desktop's. The web profile is a proposal, so this says what the proposal changes. */
  web?: string;
  /** The same value in light and dark, on purpose (the brand, a person's colour, the OS's own chrome); `text` says why. */
  sameInDark?: true;
}

